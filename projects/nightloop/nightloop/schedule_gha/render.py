"""Renders the GitHub Actions workflow text from a ``ValidSpec``.

Pure: string building only, from a list of lines; no templating library and
no YAML library. Every value placed in the text comes from a ``ValidSpec``
(whose strings matched strict patterns) or from a constant here, so the
output is deterministic and nothing a user typed can open a new YAML key or
shell command. The run command is built from ``_run_argv``, a fixed shape
with no ``--ignore-window`` (``nightloop.schedule_slot.FORBIDDEN_ARG``).
"""

from __future__ import annotations

from .spec import ValidSpec

# Third-party actions, pinned to a full commit SHA (an unattended job must not
# pick up a moved tag). Tags resolved with `git ls-remote` on 2026-11-23; all
# four are lightweight tags, so the SHA is the tagged commit.
CHECKOUT = ("actions/checkout", "3d3c42e5aac5ba805825da76410c181273ba90b1", "v7.0.1")
SETUP_PYTHON = ("actions/setup-python", "6d4fd22b20465ccc0f7354476588e8df7c9ca0e0", "v7.1.0")
SETUP_NODE = ("actions/setup-node", "949feb2413d6458794dcd2491c4babbbce0c15c1", "v7.1.0")
UPLOAD_ARTIFACT = ("actions/upload-artifact", "cf430e030ddbb5b0abf93d22962f4752f3646cd9", "v7.0.2")
RUNNER = "ubuntu-latest"
PYTHON_VERSION = "3.13"  # nightloop needs >= 3.11; the suite runs on 3.11 and 3.13
NODE_VERSION = "22"  # the Claude Code npm package needs Node 22+
CLI_PACKAGE = "@anthropic-ai/claude-code"
# The target repo and nightloop's source are checked out side by side. Neither
# may sit inside the other: an untracked directory in the target would make
# every cycle's tree dirty, and recovery would snapshot it.
TARGET_DIR = "target"
SOURCE_DIR = "nightloop-src"
PACKAGE_SUBDIR = "projects/nightloop"
# Metrics live outside the target tree, for the same reason, and are uploaded.
METRICS_DIR = "nightloop-metrics"
METRICS_FILE = f"{METRICS_DIR}/metrics.jsonl"
ARTIFACT_NAME = "nightloop-metrics"
GIT_USER_NAME = "github-actions[bot]"
GIT_USER_EMAIL = "41898282+github-actions[bot]@users.noreply.github.com"
PERMISSIONS = (("contents", "write"), ("pull-requests", "write"))


def _uses(action: tuple[str, str, str]) -> str:
    name, sha, tag = action
    return f"{name}@{sha} # {tag}"


def _run_argv(v: ValidSpec) -> tuple[str, ...]:
    """``nightloop run`` with the target, its config, the metrics file and the phase timeout."""
    return (
        "nightloop", "run",
        "--repo", TARGET_DIR,
        "--config", f"{TARGET_DIR}/{v.spec.config_path}",
        "--metrics", METRICS_FILE,
        "--timeout-s", str(v.spec.timeout_s),
    )


def _header(v: ValidSpec) -> list[str]:
    s = v.spec
    return [
        f"# Generated by `nightloop schedule-gha` from {s.config_path}.",
        "# Re-run the generator instead of editing: the cron hour, the job timeout and",
        "# the phase timeout were checked against that config's window and cycles when",
        "# this file was made, and changing either without regenerating breaks the checks.",
        f"# Worst case: {v.cycles} cycle(s) x {v.phases} phases at --timeout-s {s.timeout_s},",
        f"# about {v.needed_minutes} minutes with slack, within timeout-minutes {s.job_timeout_minutes}.",
        "# A late or dropped scheduled run is normal on GitHub; `nightloop run` refuses",
        "# to start outside the window (exit 3), and that is not a fault.",
        f"name: {s.workflow_stem}",
        "",
    ]


def _triggers(v: ValidSpec) -> list[str]:
    s = v.spec
    return [
        "on:",
        "  schedule:",
        f'    - cron: "{v.minute} {v.hour} * * *"',
        f'      timezone: "{s.timezone}"',
        "  workflow_dispatch:",
        "",
    ]


def _policy(v: ValidSpec) -> list[str]:
    lines = ["permissions:"]
    lines += [f"  {scope}: {level}" for scope, level in PERMISSIONS]
    lines += [
        "",
        "concurrency:",
        f"  group: nightloop-{v.spec.workflow_stem}",
        "  cancel-in-progress: false",
        "",
    ]
    return lines


def _job(v: ValidSpec) -> list[str]:
    s = v.spec
    secret = s.credential.value
    return [
        "jobs:",
        "  night:",
        f"    runs-on: {RUNNER}",
        f"    timeout-minutes: {s.job_timeout_minutes}",
        "    env:",
        f'      TZ: "{s.timezone}"',
        '      DISABLE_AUTOUPDATER: "1"',
        "    steps:",
        "      - name: Check out the repo with full history",
        f"        uses: {_uses(CHECKOUT)}",
        "        with:",
        f"          path: {TARGET_DIR}",
        "          fetch-depth: 0",
        "      - name: Check out nightloop at a pinned commit",
        f"        uses: {_uses(CHECKOUT)}",
        "        with:",
        f"          repository: {s.nightloop_repo}",
        f"          ref: {s.nightloop_sha}",
        f"          path: {SOURCE_DIR}",
        "          persist-credentials: false",
        "      - name: Set up Python",
        f"        uses: {_uses(SETUP_PYTHON)}",
        "        with:",
        f'          python-version: "{PYTHON_VERSION}"',
        "      - name: Set up Node",
        f"        uses: {_uses(SETUP_NODE)}",
        "        with:",
        f'          node-version: "{NODE_VERSION}"',
        "      - name: Install Claude Code and nightloop",
        "        run: |",
        f"          npm install -g {CLI_PACKAGE}@{s.claude_version}",
        f"          python -m pip install ./{SOURCE_DIR}/{PACKAGE_SUBDIR}",
        "      - name: Set the git identity for the ship commit",
        f"        working-directory: {TARGET_DIR}",
        "        run: |",
        f'          git config user.name "{GIT_USER_NAME}"',
        f'          git config user.email "{GIT_USER_EMAIL}"',
        "      - name: Run one night",
        "        env:",
        f"          {secret}: ${{{{ secrets.{secret} }}}}",
        "          GH_TOKEN: ${{ github.token }}",
        f"        run: {' '.join(_run_argv(v))}",
        "      - name: Upload the metrics",
        "        if: always()",
        f"        uses: {_uses(UPLOAD_ARTIFACT)}",
        "        with:",
        f"          name: {ARTIFACT_NAME}",
        f"          path: {METRICS_DIR}/",
        "          if-no-files-found: warn",
    ]


def render_workflow(v: ValidSpec) -> str:
    """The whole workflow file for ``v``: same input, same bytes; ends with one newline.

    Never raises for a ``ValidSpec``.
    """
    lines = _header(v) + _triggers(v) + _policy(v) + _job(v)
    return "\n".join(lines) + "\n"

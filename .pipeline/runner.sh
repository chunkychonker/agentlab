#!/bin/bash
# runner.sh — renders the launchd job that runs the nightly pipeline from a
# dedicated runner clone.
#
# Sourced by setup_runner.sh. Pure: prints text, reads and writes nothing.
# Covered offline by test_runner.sh.
#
# Why a runner clone: the night used to run in ~/agentlab, the same working
# tree the human edits. A tracked edit left there aborted the night (the dirty
# `main` preflight), and a night's scrub could delete untracked work. A git
# worktree cannot fix that — two worktrees cannot both check out `main`. A
# separate clone can; changes reach it only through merged PRs.

RUNNER_LABEL="com.steeb.agentlab.daily"

# launchd gives a minimal PATH. run.sh exports its own PATH, so this only has
# to find bash; it mirrors run.sh's for anything launchd itself resolves.
RUNNER_LAUNCHD_PATH="/Users/steeb/.local/bin:/opt/homebrew/bin:/usr/local/bin:/Library/Frameworks/Python.framework/Versions/3.13/bin:/usr/bin:/bin:/usr/sbin:/sbin"

# render_runner_plist <runner_dir>
# Prints the LaunchAgent plist for $RUNNER_LABEL: bash <runner_dir>/.pipeline/
# run.sh daily at 02:00 local time, working directory <runner_dir>, stdout and
# stderr to <runner_dir>/logs/. Returns 0. Returns 2, printing nothing, when
# <runner_dir> is not an absolute path, ends in "/", or contains a character
# that would need XML escaping (& < > " ').
render_runner_plist () {
  local dir="${1:-}"
  case "$dir" in
    /*) ;;
    *) return 2 ;;
  esac
  case "$dir" in
    */|*[\&\<\>\"\']*) return 2 ;;
  esac
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$RUNNER_LABEL</string>

    <!-- Generated by .pipeline/setup_runner.sh; edit that, not this file.
         Runs from the dedicated runner clone so a night never shares a
         working tree with interactive work. -->
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>$dir/.pipeline/run.sh</string>
    </array>

    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>$RUNNER_LAUNCHD_PATH</string>
    </dict>

    <key>WorkingDirectory</key>
    <string>$dir</string>

    <!-- 02:00 local time (America/Chicago) daily. Moved off 21:00 so a ~1h Opus
         job stops sharing a rolling 5-hour usage window with interactive
         evening work; moved off 02:47 to a round 02:00 by request.
         launchd runs a missed job on next wake, so if the Mac is asleep at
         02:00 this fires whenever the lid next opens — the pmset wake schedule
         (\`pmset -g sched\`) is what keeps that from landing mid-workday.
         INVARIANT: the wakeorpoweron time must stay EARLIER than this slot. -->
    <key>StartCalendarInterval</key>
    <dict>
        <key>Hour</key>
        <integer>2</integer>
        <key>Minute</key>
        <integer>0</integer>
    </dict>

    <key>RunAtLoad</key>
    <false/>

    <key>StandardOutPath</key>
    <string>$dir/logs/launchd.out.log</string>
    <key>StandardErrorPath</key>
    <string>$dir/logs/launchd.err.log</string>
</dict>
</plist>
EOF
  return 0
}
